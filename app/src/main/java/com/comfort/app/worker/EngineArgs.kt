internal data class SpotifyArgs(
    val url: String,
    val downloadDir: String = "",
    val cookies: String = "",
    val filenameFormat: String = "",
    val archive: String = "",
    val jsRuntime: String = "",
    val ffmpeg: String = "",
    val ffmpegLibDir: String = "",
    val aria2: String = "",
    val aria2LibDir: String = "",
    val restrictFilenames: Boolean = false,
    val trimFilenames: Boolean = false,
    val verbose: Boolean = false,
    val saveThumbnail: Boolean = false,
    val playlistItems: String = "",
    val overrideTitle: String = "",
    val overrideArtist: String = "",
    val impersonate: Boolean = false,
    val youtubeClientRotation: Boolean = false,
    val extractorArgs: String = "",
    val proxy: String = "",
    val socketTimeout: String = "",
    val retries: String = "",
    val audioFormat: String = "",
    val normalizeAudio: Boolean = false,
) {
    fun toArgs() = listOf(
        "download", url, downloadDir, cookies,
        filenameFormat, archive, jsRuntime,
        ffmpeg, ffmpegLibDir, aria2, aria2LibDir,
        flag(restrictFilenames),
        flag(trimFilenames),
        flag(verbose),
        flag(saveThumbnail),
        playlistItems,
        overrideTitle,
        overrideArtist,
        flag(impersonate),
        flag(youtubeClientRotation),
        extractorArgs,
        proxy,
        socketTimeout,
        retries,
        audioFormat,
        flag(normalizeAudio),
    )

    /** What spotify_wrapper.download hands yt_dlp_wrapper.download for each matched track —
     * everything else is left at download()'s defaults. */
    fun perTrack(matchedUrl: String) = YtDlpArgs(
        url = matchedUrl, downloadDir = downloadDir, cookies = cookies, filenameFormat = filenameFormat,
        archive = archive, jsRuntime = jsRuntime, ffmpeg = ffmpeg, ffmpegLibDir = ffmpegLibDir,
        audioOnly = true, restrictFilenames = restrictFilenames, trimFilenames = trimFilenames,
        verbose = verbose, aria2 = aria2, aria2LibDir = aria2LibDir, saveThumbnail = saveThumbnail,
        impersonate = impersonate, youtubeClientRotation = youtubeClientRotation,
        extractorArgs = extractorArgs, proxy = proxy, socketTimeout = socketTimeout, retries = retries,
        audioFormat = audioFormat, normalizeAudio = normalizeAudio,
        // download()'s own default.
        noPlaylist = true,
    )
}

