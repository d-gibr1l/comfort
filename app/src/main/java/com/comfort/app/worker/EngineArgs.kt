package com.comfort.app.worker

/** Each wrapper script's positional arguments by name. [toArgs] is the order its `__main__` block
 * reads them in (`a[0]` is the item after "download"), "" meaning "not set" — so a new argument
 * goes on the end of both. The same object is what [CommandPreview] shows as a command line, so
 * the preview can't drift from what a download actually runs with. */
internal data class YtDlpArgs(
    val url: String,
    val downloadDir: String = "",
    val cookies: String = "",
    val filenameFormat: String = "",
    val extraArgs: String = "",
    val archive: String = "",
    val limitRate: String = "",
    val formatOverride: String = "",
    val jsRuntime: String = "",
    val ffmpeg: String = "",
    val audioOnly: Boolean = false,
    val downloadSubtitles: Boolean = false,
    val subtitleLangs: String = "",
    val embedThumbnail: Boolean = false,
    val embedMetadata: Boolean = false,
    val noPlaylist: Boolean = false,
    val resolutionCap: String = "",
    val outputFormat: String = "",
    val retries: String = "",
    val playlistItems: String = "",
    val maxFilesize: String = "",
    val writeInfoFiles: Boolean = false,
    val clipRange: String = "",
    val proxy: String = "",
    val liveFromStart: Boolean = false,
    val extractorArgs: String = "",
    val saveThumbnail: Boolean = false,
    val forceIpv4: Boolean = false,
    val concurrentFragments: String = "",
    val noCheckCertificates: Boolean = false,
    val sleepInterval: String = "",
    val customHeaders: String = "",
    val formatSort: String = "",
    val verbose: Boolean = false,
    val embedChapters: Boolean = false,
    val saveSubtitleFiles: Boolean = false,
    val restrictFilenames: Boolean = false,
    val trimFilenames: Boolean = false,
    val fragmentRetries: String = "",
    val socketTimeout: String = "",
    val bufferSizeKb: String = "",
    val youtubeClientRotation: Boolean = false,
    val impersonate: Boolean = false,
    val aria2: String = "",
    val aria2LibDir: String = "",
    val ffmpegLibDir: String = "",
    val overrideTitle: String = "",
    val overrideArtist: String = "",
    val infoCache: String = "",
    val audioFormat: String = "",
    val normalizeAudio: Boolean = false,
    val sponsorBlockRemove: String = "",
    val sponsorBlockMark: String = "",
    val splitChapters: Boolean = false,
    val audioLanguage: String = "",
    // Settings' "both" set plus the download's own extra commands; extraArgs is yt-dlp's own set.
    val sharedExtraArgs: String = "",
    // A requested subtitle language with no uploaded track gets the auto-generated one.
    val subtitleAuto: Boolean = false,
) {
    fun toArgs() = listOf(
        "download", url, downloadDir, cookies,
        filenameFormat, extraArgs, archive, limitRate, formatOverride,
        jsRuntime, ffmpeg,
        flag(audioOnly), flag(downloadSubtitles), subtitleLangs,
        flag(embedThumbnail), flag(embedMetadata), flag(noPlaylist),
        resolutionCap,
        outputFormat, retries, playlistItems, maxFilesize,
        flag(writeInfoFiles), clipRange, proxy,
        flag(liveFromStart), extractorArgs,
        flag(saveThumbnail),
        flag(forceIpv4),
        concurrentFragments,
        flag(noCheckCertificates),
        sleepInterval,
        customHeaders,
        formatSort,
        flag(verbose),
        flag(embedChapters),
        flag(saveSubtitleFiles),
        flag(restrictFilenames),
        flag(trimFilenames),
        fragmentRetries,
        socketTimeout,
        bufferSizeKb,
        flag(youtubeClientRotation),
        flag(impersonate),
        aria2,
        aria2LibDir,
        ffmpegLibDir,
        overrideTitle,
        overrideArtist,
        infoCache,
        audioFormat,
        flag(normalizeAudio),
        sponsorBlockRemove,
        sponsorBlockMark,
        flag(splitChapters),
        audioLanguage,
        sharedExtraArgs,
        flag(subtitleAuto),
    )
}

